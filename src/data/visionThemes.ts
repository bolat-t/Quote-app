// Returns the theme for the ISO week containing dateStr — cycles weekly.
export const getThemeForDate = (dateStr: string): VisionTheme => {
    const [year, month, day] = dateStr.split('-').map(Number);
    const ref = new Date(2024, 0, 1); // reference: 2024-01-01
    const cur = new Date(year, month - 1, day);
    const daysSinceRef = Math.round((cur.getTime() - ref.getTime()) / 86_400_000);
    const weeksSinceRef = Math.floor(daysSinceRef / 7);
    const index = ((weeksSinceRef % VISION_THEMES.length) + VISION_THEMES.length) % VISION_THEMES.length;
    return VISION_THEMES[index];
};
